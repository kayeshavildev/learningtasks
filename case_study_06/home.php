<h3><i>PH, Germany celebrate 7-decade ties, vow stronger partnership</i></h3>
<p>MANILA – The Philippines and Germany reaffirmed their commitment to strengthening relations Tuesday as they celebrated over seven decades of diplomatic ties during a state luncheon hosted by President Ferdinand R. Marcos Jr. for German President Frank-Walter Steinmeier.

In his toast remarks delivered at Malacañan Palace in Manila, Marcos underscored the importance of continued friendship, enhanced cooperation and shared prosperity between the two nations, recognizing Germany as a key partner of the Philippines in national development.
<br><br>
He welcomed the official German delegation with the country’s trademark hospitality and raised a toast to the continued good health and success of Steinmeier and his spouse, as well as to Filipinos and Germans working together in pursuit of peace.</p>
